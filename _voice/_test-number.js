const N = require('./cn-number.js');
/* 口径：千/万 位的 2 读「两」（口语、也是支付宝的读法），百位读「二百」。
   下面三条我第一次写反了——1000 是一千不是两千；12800/25000 是口语的两。 */
const CASES = [
  [1,'一'],[9,'九'],[10,'十'],[11,'十一'],[15,'十五'],[20,'二十'],[86,'八十六'],
  [100,'一百'],[101,'一百零一'],[110,'一百一十'],[120,'一百二十'],[200,'二百'],
  [999,'九百九十九'],[1000,'一千'],[1005,'一千零五'],[1050,'一千零五十'],
  [1280,'一千二百八十'],[1500,'一千五百'],[2000,'两千'],[3000,'三千'],
  [4520,'四千五百二十'],[9999,'九千九百九十九'],
  [10000,'一万'],[10500,'一万零五百'],[12800,'一万两千八百'],
  [20000,'两万'],[25000,'两万五千'],[100000,'十万'],[123456,'十二万三千四百五十六']
];
let bad = 0;
for (const [n, want] of CASES) {
  const got = N.toText(n);
  const ok = got === want;
  if (!ok) bad++;
  console.log((ok ? '  OK   ' : '  ✗    ') + String(n).padStart(7) + ' → ' + got + (ok ? '' : '   期望 ' + want));
}
console.log('\n片段清单 ' + N.allClips().length + ' 个：' + N.allClips().join(' '));
console.log('整句示例：' + JSON.stringify(N.utterance(1280)));
console.log(bad ? `\n===== ${bad} 项不符 =====` : '\n===== 全部符合 =====');
process.exit(bad ? 1 : 0);
